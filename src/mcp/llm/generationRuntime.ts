/**
 * Coordinates external LLM providers and generated task artifacts.
 * Responsibility: This module owns memory promotion, scoped generation,
 * report generation, Tier summary generation, and persistence of generated task artifacts.
 * Non-responsibility: This module does not register MCP tools, initialize the protocol server, or own process lifecycle.
 *
 * 外部LLM Providerと生成されたタスク成果物を調整します。
 * 責務: このモジュールは、メモリ昇格、scoped generation、
 * report generation、Tier summary生成、および生成されたタスク成果物の永続化を担当します。
 * 非責務: このモジュールは、MCPツール登録、プロトコルサーバ初期化、プロセスライフサイクルを担当しません。
 *
 * @packageDocumentation
 */
